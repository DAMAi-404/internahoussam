-- Mahroussa Pro: schema (docs/ARCHITECTURE.md §3). Quantities are integers in base units.
-- Clients never write these tables directly: every mutation goes through a SECURITY DEFINER function.

-- pgcrypto lives in the `extensions` schema on Supabase (already installed there).
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create type public.user_role as enum ('owner', 'deputy', 'shop', 'labo');
create type public.quantity_mode as enum ('count', 'weight', 'volume', 'pack');
create type public.order_status as enum ('submitted', 'in_review', 'validated', 'refused', 'in_preparation', 'ready', 'received', 'cancelled');
create type public.line_decision as enum ('accepted', 'reduced', 'refused');
create type public.prep_status as enum ('todo', 'done', 'partial', 'not_done');
create type public.team_code as enum ('matin', 'nuit');

create table public.shops (
  id text primary key,
  code text not null unique check (code ~ '^[A-Z]{3}$'),
  name_fr text not null,
  name_ar text not null,
  sort int not null default 0,
  active boolean not null default true
);

create table public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role public.user_role not null,
  shop_id text references public.shops (id),
  display_name text not null,
  locale text not null default 'ar' check (locale in ('fr', 'ar')),
  check ((role = 'shop') = (shop_id is not null))
);

create table public.categories (
  id text primary key,
  name_fr text not null,
  name_ar text not null,
  sort int not null,
  active boolean not null default true
);

create table public.products (
  id text primary key default gen_random_uuid()::text,
  category_id text not null references public.categories (id),
  name_fr text not null check (char_length(name_fr) between 1 and 60),
  name_ar text not null default '' check (char_length(name_ar) <= 60),
  desc_fr text not null default '' check (char_length(desc_fr) <= 80),
  desc_ar text not null default '' check (char_length(desc_ar) <= 80),
  photo_url text,
  mode public.quantity_mode not null,
  step int not null check (step > 0),
  max_qty int check (max_qty is null or max_qty >= step),
  active boolean not null default true,
  sort int not null default 0,
  updated_at timestamptz not null default now(),
  check (mode <> 'pack' or step = 1)
);

create table public.product_packs (
  product_id text not null references public.products (id),
  id text not null,
  label text not null check (char_length(label) between 1 and 12),
  active boolean not null default true,
  sort int not null default 0,
  primary key (product_id, id)
);

create table public.labo_teams (
  code public.team_code primary key,
  pin_hash text not null
);

-- One labo device account: the active team is server-side, never trusted from the client.
create table public.labo_state (
  singleton boolean primary key default true check (singleton),
  team public.team_code,
  since timestamptz
);

create table public.orders (
  id uuid primary key, -- generated by the client: idempotency key
  code text not null unique,
  shop_id text not null references public.shops (id),
  status public.order_status not null default 'submitted',
  business_date date not null,
  version int not null default 1,
  team public.team_code,
  shop_note text not null default '' check (char_length(shop_note) <= 160),
  reviewer_role public.user_role,
  reviewer_name text,
  review_started_at timestamptz,
  edited_during_review boolean not null default false,
  submitted_at timestamptz not null default now(),
  validated_at timestamptz,
  refused_at timestamptz,
  prep_started_at timestamptz,
  ready_at timestamptz,
  received_at timestamptz,
  cancelled_at timestamptz
);
create index orders_shop_date on public.orders (shop_id, business_date);
create index orders_status_date on public.orders (status, business_date);

create table public.order_lines (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  position int not null,
  product_id text not null,
  pack_id text,
  name_fr text not null,
  name_ar text not null,
  category_id text not null,
  mode public.quantity_mode not null,
  step int not null check (step > 0),
  pack_label text,
  requested int not null check (requested > 0),
  approved int not null check (approved >= 0 and approved <= requested),
  decision public.line_decision not null default 'accepted',
  refusal_reason text check (char_length(refusal_reason) <= 80),
  prep public.prep_status not null default 'todo',
  prepared_qty int,
  labo_reason text check (char_length(labo_reason) <= 80),
  prep_team public.team_code,
  changed_by_shop boolean not null default false,
  check ((decision = 'refused') = (refusal_reason is not null)),
  check ((prep in ('partial', 'not_done')) = (labo_reason is not null)),
  check ((prep = 'partial') = (prepared_qty is not null)),
  check (prep <> 'partial' or (prepared_qty > 0 and prepared_qty < approved))
);
create index order_lines_order on public.order_lines (order_id, position);

create table public.order_notes (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  line_id uuid references public.order_lines (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 160),
  author_role public.user_role not null,
  author_name text not null,
  created_at timestamptz not null default now(),
  check (line_id is null or char_length(body) <= 80)
);
create index order_notes_order on public.order_notes (order_id);

-- Append-only audit trail. Only purge_old_orders() deletes (with the order, via cascade).
create table public.order_events (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  type text not null,
  from_status public.order_status,
  to_status public.order_status,
  actor_user uuid,
  actor_role public.user_role not null,
  actor_name text not null,
  team public.team_code,
  line_id uuid,
  detail text,
  created_at timestamptz not null default now()
);
create index order_events_order on public.order_events (order_id, id);

create table public.notifications (
  id bigint generated always as identity primary key,
  recipient text not null, -- 'owner' | 'deputy' | 'labo' | 'shop:<id>'
  type text not null,
  order_id uuid references public.orders (id) on delete cascade,
  params jsonb not null default '{}',
  push boolean not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index notifications_recipient on public.notifications (recipient, created_at desc);

create table public.push_subscriptions (
  endpoint text primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  recipient text not null,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table public.scheduled_sent (
  key text primary key,
  created_at timestamptz not null default now()
);

-- Statistics kept 13 months after the 30-day purge (PRD STA-7).
create table public.daily_totals (
  business_date date not null,
  shop_id text not null,
  product_id text not null,
  pack_label text not null default '',
  mode public.quantity_mode not null,
  name_fr text not null,
  name_ar text not null,
  category_id text not null,
  lines int not null,
  refused_lines int not null,
  problem_lines int not null,
  quantity int not null, -- prepared quantity in base units (partial counts what was prepared)
  primary key (business_date, shop_id, product_id, pack_label)
);

create table public.daily_shop_stats (
  business_date date not null,
  shop_id text not null,
  orders int not null,
  refused_orders int not null,
  median_review_min int,
  median_ready_min int,
  primary key (business_date, shop_id)
);

create table public.purge_runs (
  id bigint generated always as identity primary key,
  ran_at timestamptz not null default now(),
  cutoff_date date not null,
  orders_deleted int not null
);
